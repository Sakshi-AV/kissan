// Current active language helper
function getCurrentLanguage() {
  return localStorage.getItem('kissan_cart_lang') || 'en';
}

function setLanguage(lang) {
  if (translations[lang]) {
    localStorage.setItem('kissan_cart_lang', lang);
    applyTranslations(lang);
    document.documentElement.lang = lang;
  }
}

function t(key) {
  const currentLang = getCurrentLanguage();
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  // Fallback to English
  return translations.en[key] || key;
}

function applyTranslations(lang) {
  const selectedLang = lang || getCurrentLanguage();
  const dict = translations[selectedLang] || translations.en;

  // Apply to text content
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Apply to placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Update language select dropdowns if present
  document.querySelectorAll('#languageSelect').forEach((select) => {
    select.value = selectedLang;
  });
}

// Auto-run on DOMContentLoaded
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLanguage());
  });
}
